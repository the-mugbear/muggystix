"""The session prompt — what an agent that drives the API with curl is given.

One prompt for one project session.  It says who the agent acts for, the rules
it works under (rendered from ``agent_policy``, the same text the MCP opening
instructions render), how to connect, and where the guide is.  The how-to for
each kind of work is the guide's (``documentation/AGENT_GUIDE.md``), not this
file's: prompt = identity + skeleton.

An agent connected over MCP never sees this prompt — its client is handed a
config, and what it reads at start is ``mcp_assist._server_instructions``.

``PROMPT_VERSION`` MUST be bumped whenever the instruction content changes in a
way that affects agent behavior, and ``PROMPT_CHANGES`` rewritten to say what
this version changed.  Earlier versions are in CHANGELOG.md.
"""

import logging
from typing import Optional

from fastapi import Request

from app.core.config import settings
from app.services.agent_policy import (
    render_read_back,
    render_key_expiry_guidance,
    render_safety_rules,
)

logger = logging.getLogger(__name__)

# The version stamped on every session prompt, the served guide and each
# session row.  Dotted numeric.
PROMPT_VERSION = "4.23.0"

# What PROMPT_VERSION changed (the current version only).  Read by people
# working on BlueStick; it is not sent to agents.
PROMPT_CHANGES = (
    "The host query has a new word, `gap:<kind of evidence>` (port_discovery, "
    "service_detection, os_detection, vuln_assessment, web_tls, auth_smb_ad, "
    "validation): the hosts that kind of evidence applies to and that nothing "
    "imported so far provides it for — an Evidence gap as a host list. The "
    "guide's query reference and the coverage tool's description name it. "
    "Nothing else an agent is told changed."
)


_INSTANCE_ID_CACHE: Optional[str] = None


def _load_instance_id() -> Optional[str]:
    """Look up the system identity UUID for the provenance block.

    Returns None if the row isn't seeded yet (first boot). Logs at exception
    level for any other failure so a real bootstrap problem surfaces.
    """
    global _INSTANCE_ID_CACHE
    if _INSTANCE_ID_CACHE is not None:
        return _INSTANCE_ID_CACHE
    from sqlalchemy.exc import OperationalError, ProgrammingError
    try:
        from app.db.session import SessionLocal
        from app.db.models_auth import SystemIdentity
        with SessionLocal() as db:
            row = db.query(SystemIdentity).order_by(SystemIdentity.id).first()
            _INSTANCE_ID_CACHE = row.instance_id if row else None
            return _INSTANCE_ID_CACHE
    except (OperationalError, ProgrammingError) as exc:
        logger.warning(
            "system_identity lookup failed (db or schema unavailable); "
            "provenance block will show '(pending)': %s", exc,
        )
        return None
    except Exception:
        logger.exception(
            "Unexpected error loading system_identity for provenance block; "
            "provenance block will show '(pending)' but check the bootstrap path"
        )
        return None


def build_provenance_block(
    *,
    base_url: str,
    user_label: str,
    user_id: Optional[int],
    target_label: str,
    timestamp_iso: str,
) -> str:
    """Who generated this prompt, for what, and the one identity check."""
    instance_id = _load_instance_id() or "(pending — retry after first boot)"
    origin = base_url.rsplit("/api/v1", 1)[0]
    user_suffix = f" (id {user_id})" if user_id is not None else ""
    return (
        f"## Provenance\n\n"
        f"Generated by BlueStick instance `{instance_id}` at {timestamp_iso} "
        f"for {user_label}{user_suffix}: {target_label}. Instance: {origin}\n\n"
        f"Verify once before starting: `curl -sS {origin}/.well-known/networkmapper.json` "
        f"must answer `\"instance_id\": \"{instance_id}\"` and "
        f"`\"name\": \"BlueStick\"`. If either differs, stop and tell the "
        f"operator. An empty answer or a curl error is a connection or "
        f"certificate problem, not a mismatch (see Certificate).\n\n"
        f"---\n\n"
    )


def resolve_base_url(request: Optional[Request]) -> str:
    """Return the externally-reachable ``{origin}/api/v1`` base URL."""
    cors = settings.CORS_ORIGINS
    if cors:
        origin = cors[0].rstrip("/")
    elif request is not None:
        fwd_host = request.headers.get("x-forwarded-host")
        if fwd_host:
            scheme = request.headers.get("x-forwarded-proto", "https")
            origin = f"{scheme}://{fwd_host}"
        else:
            host_hdr = request.headers.get("host", "localhost:3000")
            scheme = request.url.scheme
            origin = f"{scheme}://{host_hdr}"
    else:
        origin = "https://localhost:3000"
    return f"{origin}/api/v1"


def _feedback_section(base_url: str) -> str:
    """When to file feedback, and the smallest body that files it.

    The full payload, who reads it and what makes an entry useful are the
    guide's.  ``source`` is required by the endpoint, so the one clause about
    it stays here.
    """
    return (
        f"### Feedback — file it when the friction happens\n"
        f"The trigger is an event, not the end of the session. The moment you "
        f"retry a call, guess at a field or a route (a 404 on a path you "
        f"expected counts) or work around something, "
        f"`POST {base_url}/agent/feedback`:\n\n"
        f"```json\n"
        f'{{"source": "testing", "prompt_version": "{PROMPT_VERSION}", '
        f'"friction_notes": "<endpoint>: expected X, got Y"}}\n'
        f"```\n\n"
        f"`source`: whichever of `assist`, `reconnaissance`, `testing` is "
        f"closest. One line is enough, and several submissions in a session "
        f"are normal; the guide has the full shape.\n\n"
    )


def _integration_block(integrations: list) -> str:
    """The scanner credentials the operator configured — facts only.

    Nothing is printed when none is configured, and nothing here says how to
    use a scanner: which tool and which parameters is the agent's judgment
    and the operator's call.

    The ``  - <Label>: `<value>``` bullet shape is a contract:
    ``prompt_sanitizer.sanitize_for_llm`` redacts those values by label before
    any text is sent to a hosted LLM (``POST /llm-providers/{id}/complete``),
    and ``tests/test_prompt_sanitizer.py`` pins the labels.  Change a label
    here and there together.  The pasted prompt keeps the plaintext: the
    operator who configured the integration is the one pasting it.
    """
    if not integrations:
        return ""
    lines = ["### Scanner credentials the operator configured\n"]
    for i in integrations:
        itype = i.get("integration_type", "generic_api")
        name = i.get("name") or "(unnamed)"
        base = i.get("base_url") or "(no base URL)"
        extra = i.get("extra_config") if isinstance(i.get("extra_config"), dict) else {}
        if itype == "nessus":
            max_hosts = extra.get("max_hosts_per_scan")
            cap = f"  - License cap: {max_hosts} hosts per scan\n" if max_hosts else ""
            lines.append(
                f"- **Nessus — `{name}`**\n"
                f"  - URL: `{base}`\n"
                f"  - Access key: `{i.get('secret') or '(missing)'}`\n"
                f"  - Secret key: `{i.get('secret2') or '(missing)'}`\n"
                f"{cap}"
            )
        elif itype == "openvas":
            lines.append(
                f"- **OpenVAS / Greenbone — `{name}`**\n"
                f"  - URL: `{base}` · GMP port: `{extra.get('gmp_port', 9390)}`\n"
                f"  - Username: `{i.get('secret') or '(missing)'}`\n"
                f"  - Password: `{i.get('secret2') or '(missing)'}`\n"
            )
        elif itype == "nuclei":
            lines.append(
                f"- **Nuclei — `{name}`**\n"
                f"  - PDCP token: `{i.get('secret') or '(not set)'}`\n"
            )
        elif itype == "burp":
            lines.append(
                f"- **Burp — `{name}`**\n"
                f"  - URL: `{base}`\n"
                f"  - API key: `{i.get('secret') or '(missing)'}`\n"
            )
        else:
            lines.append(
                f"- **{itype} — `{name}`**\n"
                f"  - URL: `{base}`\n"
                f"  - Secret: `{i.get('secret') or '(not set)'}`\n"
            )
    lines.append("\n")
    return "".join(lines)


def build_session_instructions(
    *,
    request: Optional[Request],
    session_id: int,
    project_id: int,
    project_name: str,
    purpose: Optional[str],
    raw_api_key: str,
    user_label: str,
    user_id: Optional[int],
    integrations: Optional[list] = None,
    resumed: bool = False,
) -> str:
    """The session-start prompt for a project agent session.

    Conditional parts: the resumed-session notice (``resumed``), the
    operator's stated purpose, and the configured scanner credentials.
    """
    from datetime import datetime, timezone
    base_url = resolve_base_url(request)
    guide_url = f"{base_url}/agents-guide"

    provenance = build_provenance_block(
        base_url=base_url,
        user_label=user_label,
        user_id=user_id,
        target_label=f"project #{project_id} ({project_name}), agent session #{session_id}",
        timestamp_iso=datetime.now(timezone.utc).isoformat(),
    )

    resume_notice = ""
    if resumed:
        resume_notice = (
            "> **⟳ RESUMED SESSION.** Same session, new key; the previous key "
            "is revoked. An earlier agent process may have died mid-command. "
            "Before running anything, check the working directory for output "
            "that was never uploaded, and read what this session already did "
            f"(`GET /agent/host-tests?agent_session_id={session_id}`, "
            f"`GET /agent/evidence?agent_session_id={session_id}`) so you "
            "continue rather than repeat.\n\n"
        )

    purpose_line = (
        f"**The operator stated this purpose:** {purpose.strip()}\n\n"
        if purpose and purpose.strip() else ""
    )

    return (
        provenance +
        resume_notice +
        f"## Agent Session #{session_id} — project {project_name} (id {project_id})\n\n"
        f"You act as **{user_label}** in this one project, with their project "
        f"role, checked on every call. A 403 means their role does not permit "
        f"that call: tell them, do not route around it. BlueStick runs no "
        f"commands. Everything you run, runs on {user_label}'s machine, and "
        f"BlueStick knows only what you report to it; every call you make is "
        f"recorded and shown to them.\n\n"
        + purpose_line
        + render_read_back() + "\n"
        + render_safety_rules() + "\n"
        f"### Connection\n"
        f"**Base URL:** {base_url}/agent · **Auth header (every request):** "
        f"`X-API-Key: {raw_api_key}`\n"
        f"Certificate: issued by the operator's local root CA. Use `curl -sS` "
        f"(with `-s` alone a failed request prints nothing), never `-k`. On a "
        f"certificate error (curl exit 60) tell the operator: the root is not "
        f"trusted on this machine yet (`ca/local-ca.sh trust-help`, or "
        f"`--cacert <root file>` on each request); add `-k` only if they say "
        f"to. In PowerShell use `curl.exe`. If your sandbox blocks curl, ask "
        f"the operator to run it.\n\n"
        f"### If your key expires\n"
        + render_key_expiry_guidance(base_url=base_url) + "\n"
        f"### What this session does, in whatever order the operator asks\n"
        f"- **Reads** under `/agent/assist/*` (inventory, findings, posture, "
        f"scanner observations) and `/agent/scopes` (what is in scope, and "
        f"target files).\n"
        f"- **Direct writes, attributed to {user_label}:** scanner output "
        f"(`POST /agent/uploads`), notes and corrections on hosts, tests "
        f"proposed on hosts (`POST /agent/host-tests`), and what you ran and "
        f"what came back (`POST /agent/evidence`).\n"
        f"- **Proposals a person accepts or rejects** (`POST /agent/proposals/*`): "
        f"anything that changes what the team has concluded or what the client "
        f"report says — report text, a new finding, promoting or dismissing a "
        f"scanner observation, an endpoint's status. Report text enters the "
        f"client report word for word: when the data is too thin for a "
        f"section, do not propose it (no guesses, no placeholders). \"Not "
        f"enough to write this\" is a valid answer.\n\n"
        f"Pass `agent_model` (the model you are running as) when you propose "
        f"tests, record evidence, propose a change or end the session. Run "
        f"anything that may take more than a minute or two in the background "
        f"and poll it; never block one tool call on a scan.\n\n"
        f"### The guide is reference\n"
        f"`curl -sS '{guide_url}' -o bluestick-guide.md`, then search it "
        f"(`grep -n '<route or word>' bluestick-guide.md`); it is too long to "
        f"print. It holds every endpoint, field and format, and the detail "
        f"behind each line above. Read the part you need when something leaves "
        f"you guessing, not all of it first. Send any long answer to a file "
        f"(`-o <file>.json`) and print only what you need.\n\n"
        + _feedback_section(base_url=base_url)
        + f"### End the session only when the operator says so\n"
        f"Finishing a task is not that: report what you did and wait. A session "
        f"with no task yet is waiting for one. When the operator says they are "
        f"finished: if you have filed no feedback yet, file it; then "
        f"`POST {base_url}/agent/session/end` with a line of `notes`. It "
        f"revokes your key, so it is the last call.\n\n"
        + _integration_block(integrations or [])
        + f"**Prompt version:** {PROMPT_VERSION}\n"
    )
