/**
 * The presentation stage's layout budget reads the advance width of every
 * glyph of the fonts the stage uses (presentation mode, 2.530.0).  The server
 * cannot read a font (no font library in its images), so this script reads
 * the SAME files the frontend ships (`@fontsource/ibm-plex-sans`,
 * `@fontsource/ibm-plex-mono`) and writes their widths, in em, to
 * `backend/app/data/presentation_metrics.json`, which the server measures by.
 *
 *   node scripts/generate-presentation-metrics.mjs           # write the table
 *   node scripts/generate-presentation-metrics.mjs --check   # exit 1 if it is stale
 *
 * `src/tests/presentationMetrics.test.ts` runs the check, so a font upgrade
 * that is not followed by a regenerated table fails the gate.  Widths are
 * rounded UP (the budget over-counts by construction), and every subset file
 * of a face (latin, latin-ext, cyrillic, …) is merged: the browser loads
 * whichever the text needs.
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import opentype from 'opentype.js';

const here = dirname(fileURLToPath(import.meta.url));
const frontend = join(here, '..');
const OUT = join(frontend, '..', 'backend', 'app', 'data', 'presentation_metrics.json');

/** The stage's faces: `<family>-<weight>-<style>`. */
export const FACES = [
  ['sans', 'ibm-plex-sans', 400, 'normal'],
  ['sans', 'ibm-plex-sans', 400, 'italic'],
  ['sans', 'ibm-plex-sans', 700, 'normal'],
  ['sans', 'ibm-plex-sans', 700, 'italic'],
  ['mono', 'ibm-plex-mono', 400, 'normal'],
  ['mono', 'ibm-plex-mono', 700, 'normal'],
];

const ceil4 = (x) => Math.ceil(x * 10000) / 10000;

export function buildMetrics() {
  const faces = {};
  const sources = {};
  for (const [family, pkg, weight, style] of FACES) {
    const dir = join(frontend, 'node_modules', '@fontsource', pkg, 'files');
    const suffix = `-${weight}-${style}.woff`;
    const files = readdirSync(dir).filter((f) => f.endsWith(suffix) && !f.includes('-all-')).sort();
    if (files.length === 0) throw new Error(`no font files for ${pkg} ${weight} ${style}`);
    const widths = {};
    for (const file of files) {
      const bytes = readFileSync(join(dir, file));
      sources[`${pkg}/${file}`] = createHash('sha256').update(bytes).digest('hex');
      const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
      const em = font.unitsPerEm;
      for (let i = 0; i < font.glyphs.length; i += 1) {
        const glyph = font.glyphs.get(i);
        const codes = glyph.unicodes && glyph.unicodes.length ? glyph.unicodes : (glyph.unicode != null ? [glyph.unicode] : []);
        for (const cp of codes) {
          const w = ceil4((glyph.advanceWidth ?? 0) / em);
          const key = String(cp);
          if (!(key in widths) || widths[key] < w) widths[key] = w;
        }
      }
    }
    const ordered = Object.fromEntries(Object.entries(widths).sort((a, b) => Number(a[0]) - Number(b[0])));
    faces[`${family}-${weight}-${style}`] = ordered;
  }
  const orderedSources = Object.fromEntries(Object.entries(sources).sort());
  return {
    _about: 'Advance widths (em, rounded up) of the presentation stage fonts, from the files the frontend ships. '
      + 'Generated by frontend/scripts/generate-presentation-metrics.mjs; do not edit by hand.',
    sources: orderedSources,
    faces,
  };
}

const serialise = (metrics) => `${JSON.stringify(metrics)}\n`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = serialise(buildMetrics());
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (current !== text) {
      console.error('presentation_metrics.json is stale: run node scripts/generate-presentation-metrics.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}

export { serialise, OUT };
